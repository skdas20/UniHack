"""Build the UniHack prototype deck into the organisers' mandatory template.

    python scripts/build_deck.py

Opens docs/UniHack_Prototype_Template.pptx, keeps every background and heading
exactly as supplied, and fills the content area of each slide. Writes
outputs/GlassBox_UniHack_Deck.pptx.

Design notes:
- The template is 10 x 5.62in (16:9). Each slide is a full-bleed background
  picture plus one heading text box, so content is added beneath the heading and
  the branding survives untouched.
- Every number in the deck is read from outputs/report.json, generated by
  `python run.py`. Nothing is typed by hand, so the deck cannot drift from what
  the code actually does.
"""

