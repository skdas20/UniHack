def textbox(slide, x, y, w, h, *, anchor=MSO_ANCHOR.TOP):
    box = slide.shapes.add_textbox(Inches(x), Inches(y), Inches(w), Inches(h))
    frame = box.text_frame
    frame.word_wrap = True
    frame.vertical_anchor = anchor
    frame.margin_left = frame.margin_right = 0
    frame.margin_top = frame.margin_bottom = 0
    return frame


def para(frame, text, *, size=12, bold=False, color=INK, space_before=0,
         space_after=4, first=False, align=PP_ALIGN.LEFT, font="Calibri",
         italic=False, line=1.05):
    p = frame.paragraphs[0] if first else frame.add_paragraph()
    p.alignment = align
    p.space_before = Pt(space_before)
    p.space_after = Pt(space_after)
    p.line_spacing = line
    run = p.add_run()
    run.text = text
    run.font.size = Pt(size)
    run.font.bold = bold
    run.font.italic = italic
    run.font.color.rgb = color
    run.font.name = font
    return p


def rich(frame, chunks, *, size=12, space_before=0, space_after=4, first=False,
         line=1.05):
    """One paragraph from (text, bold, color) chunks."""
    p = frame.paragraphs[0] if first else frame.add_paragraph()
    p.space_before = Pt(space_before)
    p.space_after = Pt(space_after)
    p.line_spacing = line
    for text, bold, color in chunks:
        run = p.add_run()
        run.text = text
        run.font.size = Pt(size)
        run.font.bold = bold
        run.font.color.rgb = color
        run.font.name = "Calibri"
    return p


def panel(slide, x, y, w, h, *, fill=WHITE, border=LINE, alpha_line=True):
    shape = slide.shapes.add_shape(MSO_SHAPE.ROUNDED_RECTANGLE,
                                   Inches(x), Inches(y), Inches(w), Inches(h))
    shape.adjustments[0] = 0.04
    shape.fill.solid()
    shape.fill.fore_color.rgb = fill
    if border is None:
        shape.line.fill.background()
    else:
        shape.line.color.rgb = border
        shape.line.width = Pt(0.75)
    shape.shadow.inherit = False
    shape.text_frame.word_wrap = True
    shape.text_frame.margin_left = Inches(0.14)
    shape.text_frame.margin_right = Inches(0.14)
    shape.text_frame.margin_top = Inches(0.10)
    shape.text_frame.margin_bottom = Inches(0.10)
    return shape


def metric_card(slide, x, y, w, h, value, label, *, tone=ACCENT):
    shape = panel(slide, x, y, w, h, fill=WHITE, border=LINE)
    frame = shape.text_frame
    frame.vertical_anchor = MSO_ANCHOR.MIDDLE
    para(frame, value, size=19, bold=True, color=tone, first=True,
         space_after=1, align=PP_ALIGN.CENTER)
    para(frame, label, size=8, color=DIM, space_after=0, align=PP_ALIGN.CENTER,
         line=0.95)
    return shape


def chip(slide, x, y, w, h, text, *, fill=ACCENT_SOFT, color=ACCENT, size=8.5):
    shape = panel(slide, x, y, w, h, fill=fill, border=None)
    frame = shape.text_frame
    frame.vertical_anchor = MSO_ANCHOR.MIDDLE
    para(frame, text, size=size, bold=True, color=color, first=True,
         space_after=0, align=PP_ALIGN.CENTER)
    return shape


def arrow_down(slide, x, y, h=0.16):
    shape = slide.shapes.add_shape(MSO_SHAPE.DOWN_ARROW, Inches(x), Inches(y),
                                  Inches(0.16), Inches(h))
    shape.fill.solid()
    shape.fill.fore_color.rgb = RGBColor(0xB6, 0xC2, 0xCC)
    shape.line.fill.background()
    shape.shadow.inherit = False
    return shape


def find_heading(slide):
    """The template's own heading box: the text shape nearest the top."""
    candidates = [s for s in slide.shapes if s.has_text_frame and s.text_frame.text.strip()]
    if not candidates:
        return None
    return min(candidates, key=lambda s: s.top)


#: Where the template puts its headings, used when a slide has none of its own.
HEADING_POS = (0.42, 0.72, 9.16, 0.62)


def set_heading(slide, text, *, size=22):
    """Set the slide heading, reusing the template's box where one exists.

    Falls back to creating a box at the template's own heading position, which
    is what the appended slides need -- they are built from a bare layout and
    so ship with no heading shape at all.
    """
    head = find_heading(slide)
    if head is None:
        frame = textbox(slide, *HEADING_POS)
        para(frame, text, size=size, bold=True, color=INK, first=True,
             space_after=0)
        return
    # Normalise the position too. The template puts its headings anywhere from
    # y=0.72in to y=1.0in, which made a fixed subtitle position overlap the
    # heading on some slides and float on others.
    head.left, head.top = Inches(HEADING_POS[0]), Inches(HEADING_POS[1])
    head.width, head.height = Inches(HEADING_POS[2]), Inches(HEADING_POS[3])
    frame = head.text_frame
    frame.clear()
    frame.vertical_anchor = MSO_ANCHOR.TOP
    p = frame.paragraphs[0]
    p.space_after = Pt(0)
    run = p.add_run()
    run.text = text
    run.font.size = Pt(size)
    run.font.bold = True
    run.font.color.rgb = INK
    run.font.name = "Calibri"


def subtitle_under_heading(slide, text, *, y=1.30, size=11):
    frame = textbox(slide, BODY_LEFT, y, BODY_WIDTH, 0.34)
    para(frame, text, size=size, color=DIM, first=True, space_after=0)


