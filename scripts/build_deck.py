def main() -> int:
    metrics = load_metrics()
    prs = Presentation(str(TEMPLATE))

    # Slides 4 and 5 of the accuracy/scalability question live on template slide
    # 4, which asks all three questions at once. Duplicate handling: we answer
    # question 1 on slide 4 and add answers 2 and 3 by reusing slides 5 and 6
    # is not possible without layout surgery, so instead the three questions are
    # answered on slides 4, and two new slides appended from the same layout.
    for index, builder in BUILDERS.items():
        slide = prs.slides[index - 1]
        # clear any body placeholder text the template shipped, keeping the
        # heading shape itself
        # Compare by shape id: python-pptx hands back a *new* wrapper object on
        # every iteration of slide.shapes, so `shape is not head` is true even
        # for the heading itself -- which silently wiped every heading in the
        # deck before this was caught by rendering the slides.
        head = find_heading(slide)
        head_id = head.shape_id if head is not None else None
        for shape in list(slide.shapes):
            if (
                shape.has_text_frame
                and shape.shape_id != head_id
                and shape.text_frame.text.strip()
            ):
                shape.text_frame.clear()
        builder(slide, metrics)
        print(f"  filled slide {index}: {builder.__name__}")

    # The accuracy and scalability answers need their own slides. A slide added
    # from a layout carries no background, because the template's branding lives
    # on each *slide* as a full-bleed picture rather than on the layout -- so the
    # background is copied across explicitly.
    background = extract_background(prs)
    layout = prs.slides[3].slide_layout
    for builder in (slide_accuracy, slide_scale):
        slide = prs.slides.add_slide(layout)
        for shape in list(slide.shapes):
            if shape.has_text_frame:
                shape.text_frame.clear()
        if background is not None:
            picture = slide.shapes.add_picture(
                io.BytesIO(background), Inches(0), Inches(0),
                width=prs.slide_width, height=prs.slide_height,
            )
            # send it to the back so the content sits on top of it
            slide.shapes._spTree.remove(picture._element)
            slide.shapes._spTree.insert(2, picture._element)
        builder(slide, metrics)
        print(f"  appended slide: {builder.__name__}")

    drop_slides(prs, DROP)
    print(f"  dropped template slides {DROP}")

    # move the two appended slides to sit just after the enrichment answer
    ids = prs.slides._sldIdLst
    entries = list(ids)
    # after DROP, slide order is: team, brief, enrich, opportunities, features,
    # flow, architecture, tech, mvp, future, links, closing, accuracy, scale
    accuracy, scale = entries[-2], entries[-1]
    ids.remove(accuracy)
    ids.remove(scale)
    enrich_pos = 2  # 0-based index of the enrichment slide
    ids.insert(enrich_pos + 1, accuracy)
    ids.insert(enrich_pos + 2, scale)

    OUT.parent.mkdir(parents=True, exist_ok=True)
    prs.save(str(OUT))
    size_kb = OUT.stat().st_size / 1024
    print(f"\nwrote {OUT}  ({size_kb:.0f} KB, {len(prs.slides.__iter__.__self__._sldIdLst)} slides)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
