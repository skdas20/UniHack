def extract_background(prs) -> bytes | None:
    """The full-bleed branding picture, taken from whichever slide carries one."""
    for slide in prs.slides:
        for shape in slide.shapes:
            if shape.shape_type == 13 and shape.width >= prs.slide_width * 0.95:
                return shape.image.blob
    return None


def drop_slides(prs, indices_1based) -> None:
    xml_slides = prs.slides._sldIdLst
    slides = list(xml_slides)
    for index in sorted(indices_1based, reverse=True):
        rId = slides[index - 1].get(
            "{http://schemas.openxmlformats.org/officeDocument/2006/relationships}id"
        )
        prs.part.drop_rel(rId)
        xml_slides.remove(slides[index - 1])


