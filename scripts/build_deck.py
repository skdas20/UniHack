#: The row used as the worked example on the enrichment slide.
EXAMPLE_MPN = "49-94-1940"


def load_example(mpn: str = EXAMPLE_MPN) -> dict:
    """Read the worked example straight out of the enriched delivery sheet.

    Typing these values by hand is how a deck ends up claiming something the
    code does not do -- the first draft of this slide asserted Diablo / Freud
    America for a row the pipeline actually resolves to Milwaukee. Reading the
    real output makes that class of error impossible.
    """
    import csv

    path = ROOT / "outputs" / "enriched.csv"
    if not path.exists():
        raise SystemExit("outputs/enriched.csv missing. Run `python run.py` first.")
    with path.open(newline="", encoding="utf-8-sig") as fh:
        for record in csv.DictReader(fh):
            if (record.get("Mfg_Part_Num") or "").strip() == mpn:
                return record
    raise SystemExit(f"row {mpn!r} not found in outputs/enriched.csv")


def load_metrics() -> dict:
    """Every figure in the deck comes from the last real run."""
    if not REPORT.exists():
        raise SystemExit(
            "outputs/report.json missing. Run `python run.py` first so the deck "
            "quotes measured numbers rather than remembered ones."
        )
    return json.loads(REPORT.read_text(encoding="utf-8"))


